class Запись:
    """Как создать объект в тесте: внешние объекты — регистраторы, ссылки — вложенные создания.
    Возвращает структуру, а не текст: текст пишет вывод."""

    def __init__(self):
        self.внешние: list[tuple[str, str]] = []   # (переменная, объект)

    def структура(self, экз: Экз) -> tuple[str, list]:
        элементы = []
        for реквизит in экз.объект.реквизиты:
            значение = экз.реквизиты[реквизит.имя]
            if isinstance(значение, Экз):
                if значение.объект.внешний:
                    элементы.append((реквизит.имя, self._внешний(значение.объект.имя)))
                else:
                    элементы.append((реквизит.имя, self.структура(значение)))
            else:
                элементы.append((реквизит.имя, значение))
        return (экз.объект.имя, элементы)

    def _внешний(self, имя_объекта: str) -> ВнешняяСсылка:
        переменная = f"внешний_{имя_объекта.lower()}"
        if (переменная, имя_объекта) not in self.внешние:
            self.внешние.append((переменная, имя_объекта))
        return ВнешняяСсылка(переменная)


class Генератор:
    def __init__(self, объекты: dict[str, Объект], вывод: Вывод | None = None):
        self.объекты = объекты
        self.вывод = вывод or ВыводPython()
        self.подбор = Подбор(объекты)
        self.группы: dict[str, tuple[str, list]] = {}   # класс → (описание, [(имя, описание, тело)])
        self.группа = ("", "")
        for объект in объекты.values():
            for перечисление in объект.перечисления.values():
                _ЗНАЧЕНИЯ_ПЕРЕЧИСЛЕНИЙ.update(имя for имя, _ in перечисление.значения)
        self.имена: set[str] = set()

    # --- вход
    def все(self) -> str:
        for объект in self.объекты.values():
            if объект.внешний:
                continue
            self.проверить_правила(объект)
            self.группа = (f"Тест_{объект.имя}", f"{объект.имя}: реквизиты, перечисления и реализация")
            self.реквизиты(объект)
            for перечисление in объект.перечисления.values():
                self.перечисление(объект, перечисление)
            self.реализация(объект)
            for метод in объект.методы.values():
                параметры = ", ".join(п.имя for п in метод.параметры)
                self.группа = (f"Тест_{объект.имя}_{метод.имя}", f"{объект.имя}.{метод.имя}({параметры})")
                if метод.вид == "решения":
                    self.решения(объект, метод)
                else:
                    self.шаги(объект, метод)
                self.примеры(объект, метод)
                self.охрана(объект, метод)
        return self.текст()

    def проверить_правила(self, объект: Объект) -> None:
        """Ограничение — про один реквизит, инвариант — по правилу ПростоеУсловие; состояние по умолчанию их не нарушает."""
        реквизиты = {р.имя for р in объект.реквизиты}
        for реквизит in объект.реквизиты:
            for о in реквизит.ограничения:
                где = f"{объект.имя}.{реквизит.имя}: ограничение «{о.текст}»"
                узел = в.разобрать_условие(о.выражение, где)
                в.проверить_простое_условие(узел, где)
                чужие = (в.имена_в(узел) & реквизиты) - {реквизит.имя}
                if чужие:
                    raise ОшибкаСпецификации(f"{где}: упомянут реквизит {', '.join(sorted(чужие))}; "
                                             "условие на несколько реквизитов — строка таблицы Правило | Условие | Ошибка")
        for инвариант in объект.инварианты:
            где = f"{объект.имя}: инвариант «{инвариант.правило}»"
            в.проверить_простое_условие(в.разобрать_условие(инвариант.условие, где), где)
        среда = self.подбор.среда()
        правило = среда.нарушение(среда.создать(объект.имя, {}))
        if isinstance(правило, Инвариант):
            raise ОшибкаСпецификации(f"{объект.имя}: значения по умолчанию нарушают инвариант «{правило.правило}»; задайте их после «=» в колонке Тип")

    def тест(self, имя: str, описание: list[str], тело: list[str]) -> None:
        if имя in self.имена:
            raise ОшибкаСпецификации(f"имя теста {имя} повторяется")
        self.имена.add(имя)
        класс, описание_группы = self.группа
        self.группы.setdefault(класс, (описание_группы, []))[1].append((имя, описание, тело))

    def текст(self) -> str:
        return self.вывод.файл(self.группы)

    # --- таблицы данных
    def реквизиты(self, объект: Объект) -> None:
        среда = self.подбор.среда()
        экз = среда.создать(объект.имя, {})
        запись = Запись()
        создание = self.вывод.создать(*запись.структура(экз))
        тело = [self.вывод.внешний(п, о) for п, о in запись.внешние]
        тело += [
            self.вывод.присвоить("объект", создание),
            self.вывод.прочитать("объект", прочитать(экз)),
        ]
        имена = ", ".join(р.имя for р in объект.реквизиты)
        self.тест(f"test_{объект.имя}_Реквизиты", [f"Реквизиты {имена} создаются со значениями по умолчанию и читаются без потерь"], тело)

    def перечисление(self, объект: Объект, перечисление) -> None:
        значения = [имя for имя, _ in перечисление.значения]
        self.тест(f"test_{объект.имя}_{перечисление.имя}", [f"{перечисление.имя}: значения {', '.join(значения)} в этом порядке"], [
            self.вывод.перечисление(перечисление.имя, значения),
        ])

    def реализация(self, объект: Объект) -> None:
        модуль = объект.свойства.get("Модуль", "").strip("`")
        self.тест(f"test_{объект.имя}_Реализация", [f"Класс {объект.имя} есть в модуле {модуль}"], [
            self.вывод.класс_есть(объект.имя, f"в модуле {модуль} нет класса {объект.имя}"),
        ])

    # --- таблица решений
    def решения(self, объект: Объект, метод: Метод) -> None:
        где = f"{объект.имя}.{метод.имя}"
        условия = []
        for строка in метод.строки:
            условие = в.разобрать_условие(строка.условие, f"{где}: {строка.правило}")
            в.проверить_простое_условие(условие, f"{где}: {строка.правило}")
            условия.append(условие)
        for i, строка in enumerate(метод.строки):
            найдено = self.подбор.для_строки(объект, метод, условия, i)
            if найдено is None:
                if not any(п.правило == строка.правило for п in метод.примеры):
                    raise ОшибкаСпецификации(f"{где}: для строки «{строка.правило}» не подобрать состояние; добавьте таблицу Примеры")
                continue
            реквизиты, параметры = найдено
            if _пусто(строка.условие):
                когда = "иначе" if i else "всегда"
            else:
                когда = f"если {строка.условие}"
            self.прогон(объект, метод, строка.правило, реквизиты, параметры, f"test_{объект.имя}_{метод.имя}_{строка.правило}",
                        [f"{строка.правило}: {когда} → {_исход(строка)}"])

    def примеры(self, объект: Объект, метод: Метод) -> None:
        где = f"{объект.имя}.{метод.имя}: Примеры"
        среда = self.подбор.среда()
        for n, пример in enumerate(метод.примеры, 1):
            реквизиты = {} if пример.реквизиты.strip() == "—" else среда.вычислить(в.разобрать_выражение(пример.реквизиты, где), None, {}, {})
            параметры = {} if пример.параметры.strip() == "—" else среда.вычислить(в.разобрать_выражение(пример.параметры, где), None, {}, {})
            if not any(с.правило == пример.правило for с in метод.строки):
                raise ОшибкаСпецификации(f"{где}: правила «{пример.правило}» нет в методе")
            строка = next(с for с in метод.строки if с.правило == пример.правило)
            нарушено = среда.нарушение(среда.создать(объект.имя, dict(реквизиты)))
            if нарушено is not None:
                raise ОшибкаСпецификации(f"{где}: пример {n} к правилу «{пример.правило}» нарушает {_правило_человеку(нарушено)}")
            self.прогон(объект, метод, пример.правило, реквизиты, параметры, f"test_{объект.имя}_{метод.имя}_{пример.правило}_пример{n}",
                        [f"Пример {n} к правилу {пример.правило} → {_исход(строка)}"])

    def прогон(self, объект: Объект, метод: Метод, правило: str, реквизиты: dict, параметры: dict, имя: str,
               описание: list[str], сбой: tuple | None = None) -> None:
        среда = self.подбор.среда()
        среда.сбой = сбой
        экз = среда.создать(объект.имя, dict(реквизиты))
        запись = Запись()
        создание = self.вывод.создать(*запись.структура(экз))
        аргументы = [параметры[п.имя] for п in метод.параметры]
        вызов = self.вывод.вызов("объект", метод.имя, аргументы)
        тело = [self.вывод.внешний(п, о) for п, о in запись.внешние]
        тело += [self.вывод.присвоить("объект", создание), self.вывод.сейчас(среда.сейчас)]
        исход = None
        ошибка = None
        try:
            исход = среда.вызвать_метод(экз, метод.имя, аргументы)
        except ОшибкаМетода as о:
            ошибка = str(о)
        except Сбой:
            ошибка = "сбой"
        if сбой is not None:
            тело += self.вывод.сбой(вызов, сбой[0], сбой[1], сбой[2])
        elif ошибка is not None:
            тело += self.вывод.отказ(вызов, ошибка)
        elif метод.тип_ответа is not None:
            тело.append(self.вывод.ответ(вызов, исход))
        else:
            тело.append(вызов)
        тело.append(self.вывод.прочитать("объект", прочитать(экз)))
        for переменная, имя_объекта in запись.внешние:
            тело.append(self.вывод.вызовы(переменная, self._вызовы(экз, имя_объекта)))
        self.тест(имя, описание + self._вход_и_ответ(объект, метод, среда, реквизиты, параметры, экз, исход, ошибка, сбой), тело)

    def _вход_и_ответ(self, объект: Объект, метод: Метод, среда: Среда, реквизиты: dict, параметры: dict,
                     экз: Экз, исход, ошибка, сбой) -> list[str]:
        """Две строки описания: что подобрал генератор и что вычислила спецификация."""
        вход = [f"{к} = {_человеку(з)}" for к, з in реквизиты.items()
                if з != среда.по_умолчанию(объект.реквизит(к).тип, f"{объект.имя}.{к}")]
        вход += [f"{к} = {_человеку(з)}" for к, з in параметры.items()]
        строки = [f"Вход: {'; '.join(вход) if вход else 'значения по умолчанию'}"]
        до = прочитать(self.подбор.среда().создать(объект.имя, dict(реквизиты)))
        ожидается = [f"{к} = {_человеку(з)}" for к, з in прочитать(экз).items() if з != до.get(к)]
        if метод.тип_ответа is not None and сбой is None and ошибка is None:
            ожидается.insert(0, f"ответ {_человеку(исход)}")
        for значение in экз.реквизиты.values():
            if isinstance(значение, Экз) and значение.объект.внешний:
                for метод_вн, аргументы in значение.вызовы:
                    ожидается.append(f"{значение.объект.имя}.{метод_вн}({', '.join(_человеку(а) for а in аргументы)})")
        if ошибка is not None and сбой is None:
            строки.append(f"Ожидается: Ошибка «{ошибка}»" + (f"; {'; '.join(ожидается)}" if ожидается else ", ничего не меняется"))
            return строки
        строки.append(f"Ожидается: {'; '.join(ожидается) if ожидается else 'ничего не меняется'}")
        return строки

    def _вызовы(self, экз: Экз, имя_объекта: str) -> list:
        for значение in экз.реквизиты.values():
            if isinstance(значение, Экз) and значение.объект.имя == имя_объекта:
                return list(значение.вызовы)
        return []

    # --- охрана ограничений и инвариантов
    def охрана(self, объект: Объект, метод: Метод) -> None:
        """Для каждого правила, чей реквизит метод меняет, — вход, на котором после метода оно нарушилось бы."""
        где = f"{объект.имя}.{метод.имя}"
        меняет = _меняет(объект, метод)
        условия = []
        for строка in метод.строки:
            условие = в.разобрать_условие(строка.условие, f"{где}: {строка.правило}")
            условия.append(условие)
        for суффикс, правило, узел in _правила(объект):
            if not (в.имена_в(узел) & меняет):
                continue
            for реквизиты, параметры in self.подбор.состояния(объект, метод, условия + [узел]):
                о = self.подбор.исход(объект, метод, реквизиты, параметры)
                if isinstance(о, ОшибкаОхраны) and о.правило is правило:
                    self.прогон(объект, метод, суффикс, реквизиты, параметры, f"test_{объект.имя}_{метод.имя}_{суффикс}",
                                [f"{суффикс}: после метода не держится {_правило_человеку(правило)} → Ошибка «{правило.ошибка}»"])
                    break

    # --- таблица шагов
    def шаги(self, объект: Объект, метод: Метод) -> None:
        где = f"{объект.имя}.{метод.имя}"
        условия = []
        for строка in метод.строки:
            условие = в.разобрать_условие(строка.условие, f"{где}: {строка.правило}")
            в.проверить_простое_условие(условие, f"{где}: {строка.правило}")
            условия.append(условие)
        найдено = self.подбор.для_шагов(объект, метод, условия, None)
        if найдено is None:
            raise ОшибкаСпецификации(f"{где}: не подобрать состояние, где все шаги выполняются")
        реквизиты, параметры = найдено
        шаги = ", ".join(f"{с.шаг} {с.правило}" for с in метод.строки)
        self.прогон(объект, метод, "ВсеШаги", реквизиты, параметры, f"test_{объект.имя}_{метод.имя}_ВсеШаги",
                    [f"Все шаги по порядку: {шаги}"])
        for j, строка in enumerate(метод.строки):
            if условия[j] is not None:
                без = self.подбор.для_шагов(объект, метод, условия, j)
                if без is None:
                    if not any(п.правило == строка.правило for п in метод.примеры):
                        raise ОшибкаСпецификации(f"{где}: шаг {строка.шаг} {строка.правило}: не подобрать вход, где условие «{строка.условие}» "
                                                 f"перед шагом ложно; уберите условие или добавьте таблицу Примеры")
                else:
                    self.прогон(объект, метод, строка.правило, без[0], без[1], f"test_{объект.имя}_{метод.имя}_Без{строка.правило}",
                                [f"Шаг {строка.шаг} {строка.правило} пропускается: условие «{строка.условие}» ложно перед шагом"])
            отмена = [с for с in метод.строки[:j] if с.компенсация.strip() not in ("—", "-", "")]
            if отмена:
                компенсации = ", ".join(f"{с.шаг} {с.правило}" for с in reversed(отмена))
                self.прогон(объект, метод, строка.правило, реквизиты, параметры,
                            f"test_{объект.имя}_{метод.имя}_СбойНаШаге{строка.шаг}",
                            [f"Сбой на шаге {строка.шаг} {строка.правило} → компенсация шагов {компенсации}"], сбой=(объект.имя, метод.имя, строка.шаг))


_ЗНАЧЕНИЯ_ПЕРЕЧИСЛЕНИЙ: set[str] = set()   # заполняет Генератор: такие строки пишутся без кавычек


def _правила(объект: Объект) -> list:
    """(суффикс имени теста, правило, разобранное условие) для ограничений и инвариантов объекта."""
    правила = []
    for реквизит in объект.реквизиты:
        for n, о in enumerate(реквизит.ограничения, 1):
            номер = str(n) if len(реквизит.ограничения) > 1 else ""
            правила.append((f"Нарушение{реквизит.имя}{номер}", о, в.разобрать_условие(о.выражение, f"{объект.имя}.{реквизит.имя}")))
    for и in объект.инварианты:
        правила.append((f"Нарушение{и.правило}", и, в.разобрать_условие(и.условие, f"{объект.имя}: {и.правило}")))
    return правила


def _правило_человеку(правило) -> str:
    if isinstance(правило, Ограничение):
        return f"ограничение «{правило.выражение}»"
    return f"инвариант «{правило.правило}: {правило.условие}»"


def _меняет(объект: Объект, метод: Метод, видели: set | None = None) -> set[str]:
    """Реквизиты, которые метод может поменять: цели присваиваний, свои и вызванных своих методов."""
    видели = set() if видели is None else видели
    видели.add(метод.имя)
    имена: set[str] = set()

    def обойти(действия: list) -> None:
        for д in действия:
            if д[0] == "присвоить":
                цель = д[1]
                while цель[0] == "реквизит":
                    цель = цель[1]
                if цель[0] == "имя":
                    имена.add(цель[1])
            elif д[0] == "выполнить":
                вызов = д[1]
                if вызов[1] is None and вызов[2] in объект.методы and вызов[2] not in видели:
                    имена.update(_меняет(объект, объект.методы[вызов[2]], видели))
            elif д[0] == "для_каждого":
                обойти(д[3])

    где = f"{объект.имя}.{метод.имя}"
    for строка in метод.строки:
        обойти(в.разобрать_действия(строка.действия, где))
        обойти(в.разобрать_компенсацию(строка.компенсация, где))
        ответ = в.разобрать_ответ(строка.ответ, где)
        if ответ is not None and ответ[0] != "ошибка":
            for вызов in _вызовы_своих(ответ, объект, видели):
                имена.update(_меняет(объект, объект.методы[вызов], видели))
    return имена


def _вызовы_своих(узел, объект: Объект, видели: set) -> list[str]:
    """Свои методы, вызванные в выражении ответа."""
    найдено = []
    if isinstance(узел, tuple):
        if узел and узел[0] == "вызов" and узел[1] is None and узел[2] in объект.методы and узел[2] not in видели:
            найдено.append(узел[2])
        for часть in узел[1:]:
            if isinstance(часть, tuple):
                найдено += _вызовы_своих(часть, объект, видели)
            elif isinstance(часть, list):
                for э in часть:
                    найдено += _вызовы_своих(э, объект, видели)
            elif isinstance(часть, dict):
                for э in часть.values():
                    найдено += _вызовы_своих(э, объект, видели)
    return найдено


def _пусто(ячейка: str) -> bool:
    return ячейка.strip() in ("—", "-", "")


def _исход(строка) -> str:
    части = []
    if not _пусто(строка.действия):
        части.append(строка.действия)
    if not _пусто(строка.ответ):
        части.append(строка.ответ if строка.ответ.startswith("Ошибка") else f"ответ {строка.ответ}")
    return "; ".join(части) or "ничего не меняется"


def _человеку(значение) -> str:
    """Значение так, как оно записано в спецификации."""
    if значение is None:
        return "null"
    if значение is True:
        return "Истина"
    if значение is False:
        return "Ложь"
    if isinstance(значение, datetime):
        return f"Дата«{значение:%Y-%m-%d %H:%M}»"
    if isinstance(значение, str):
        return значение if значение in _ЗНАЧЕНИЯ_ПЕРЕЧИСЛЕНИЙ else f"«{значение}»"
    if isinstance(значение, list):
        return "[" + ", ".join(_человеку(э) for э in значение) + "]"
    if isinstance(значение, dict):
        return "{" + ", ".join(f"{к}: {_человеку(з)}" for к, з in значение.items()) + "}"
    if isinstance(значение, Экз):
        return значение.объект.имя
    return str(значение)

