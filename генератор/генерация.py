# ---------------------------------------------------------------- кандидаты значений

def кандидаты(тип: Тип, константы: list, среда: Среда, где: str) -> list:
    умолч = среда.по_умолчанию(тип, где)
    значения: list = [умолч]
    if тип.вид == "Булево":
        значения += [False, True]
    elif тип.вид == "Число":
        числа = {0, 1}
        for к in константы:
            if isinstance(к, (int, float)) and not isinstance(к, bool):
                числа |= {к, к - 1, к + 1}
        значения += sorted(числа)
    elif тип.вид == "Строка":
        значения += [к for к in константы if isinstance(к, str)]
    elif тип.вид == "Дата":
        значения += [ДАТА_ТЕСТА]
    elif тип.вид == "Список":
        значения += [[], [среда.по_умолчанию(тип.элемент, где)]]
    elif тип.вид == "Ссылка":
        for объект in среда.объекты.values():
            if тип.цель in объект.перечисления:
                значения += [имя for имя, _ in объект.перечисления[тип.цель].значения]
    if тип.необязательный:
        значения.append(None)
    уникальные = []
    for з in значения:
        if з not in уникальные:
            уникальные.append(з)
    return уникальные


# ---------------------------------------------------------------- подбор состояния

class Подбор:
    def __init__(self, объекты: dict[str, Объект]):
        self.объекты = объекты

    def среда(self) -> Среда:
        return Среда(self.объекты)

    def состояния(self, объект: Объект, метод: Метод, условия: list):
        """Перебор значений реквизитов и параметров, упомянутых в условиях метода.
        Состояния, нарушающие ограничение или инвариант, в перебор не попадают."""
        среда = self.среда()
        имена: set[str] = set()
        константы: list = []
        for условие in условия:
            в.имена_в(условие, имена)
            в.константы_в(условие, константы)
        # реквизит из инварианта перебирается вместе с остальными реквизитами этого инварианта:
        # иначе при Статус = Закрыта осталась бы ДатаЗакрытия по умолчанию, и состояние отсеялось бы
        инварианты = [в.разобрать_условие(и.условие, f"{объект.имя}: {и.правило}") for и in объект.инварианты]
        добавлены: set[int] = set()
        while True:
            новые = [j for j, у in enumerate(инварианты) if j not in добавлены and в.имена_в(у) & имена]
            if not новые:
                break
            for j in новые:
                добавлены.add(j)
                в.имена_в(инварианты[j], имена)
                в.константы_в(инварианты[j], константы)
        переменные = []
        for реквизит in объект.реквизиты:
            if реквизит.имя in имена:
                значения = кандидаты(реквизит.тип, константы, среда, f"{объект.имя}.{реквизит.имя}")
                переменные.append(("реквизит", реквизит.имя, [з for з in значения if среда._верно(реквизит, з)]))
        for параметр in метод.параметры:
            переменные.append(("параметр", параметр.имя, кандидаты(параметр.тип, константы, среда, f"{объект.имя}.{метод.имя}.{параметр.имя}")))
        for i, набор in enumerate(itertools.product(*[к for _, _, к in переменные])):
            if i >= ПРЕДЕЛ_ПЕРЕБОРА:
                break
            реквизиты = {имя: з for (вид, имя, _), з in zip(переменные, набор) if вид == "реквизит"}
            параметры = {имя: з for (вид, имя, _), з in zip(переменные, набор) if вид == "параметр"}
            if среда.нарушение(среда.создать(объект.имя, dict(реквизиты))) is not None:
                continue
            yield реквизиты, параметры

    def истинно(self, объект: Объект, условие, реквизиты: dict, параметры: dict) -> bool:
        if условие is None:
            return True
        среда = self.среда()
        экз = среда.создать(объект.имя, dict(реквизиты))
        return bool(среда.вычислить(условие, экз, параметры, {}))

    def для_строки(self, объект: Объект, метод: Метод, условия: list, i: int):
        """Состояние, где условия строк до i ложны, а условие строки i истинно.
        Из подходящих берётся то, где после метода ограничения и инварианты верны: охрану проверяет свой тест."""
        запасное = None
        for реквизиты, параметры in self.состояния(объект, метод, условия):
            if any(self.истинно(объект, у, реквизиты, параметры) for у in условия[:i]):
                continue
            if self.истинно(объект, условия[i], реквизиты, параметры):
                if not isinstance(self.исход(объект, метод, реквизиты, параметры), ОшибкаОхраны):
                    return реквизиты, параметры
                запасное = запасное or (реквизиты, параметры)
        return запасное

    def исход(self, объект: Объект, метод: Метод, реквизиты: dict, параметры: dict):
        """Чем кончился вызов метода по спецификации: None или исключение-отказ."""
        среда = self.среда()
        экз = среда.создать(объект.имя, dict(реквизиты))
        try:
            среда.вызвать_метод(экз, метод.имя, [параметры[п.имя] for п in метод.параметры])
        except (ОшибкаМетода, Сбой, НеЗавершается) as о:
            return о
        return None

    def для_шагов(self, объект: Объект, метод: Метод, условия: list, ложный: int | None):
        """Вход, при прогоне которого пропущен только шаг с индексом `ложный` (или ни один).
        Из подходящих берётся тот, где условие шага перед ним не такое, как на входе (+2), и стоит на границе (+1)."""
        нужно = [] if ложный is None else [метод.строки[ложный].шаг]
        важные = [j for j, у in enumerate(условия) if у is not None and ложный in (None, j)]
        лучший, лучший_балл = None, -1
        for реквизиты, параметры in self.состояния(объект, метод, условия):
            среда = self.среда()
            экз = среда.создать(объект.имя, dict(реквизиты))
            try:
                среда.вызвать_метод(экз, метод.имя, [параметры[п.имя] for п in метод.параметры])
            except ОшибкаМетода:
                continue
            if среда.пропущены != нужно:
                continue
            балл = 0
            for j in важные:
                перед = среда.перед_шагами[метод.строки[j].шаг]
                истина = self.истинно(объект, условия[j], перед, параметры)
                if self.истинно(объект, условия[j], реквизиты, параметры) != истина:
                    балл += 2
                if self.на_границе(объект, условия[j], перед, параметры, истина):
                    балл += 1
            if балл > лучший_балл:
                лучший, лучший_балл = (реквизиты, параметры), балл
        return лучший

    def на_границе(self, объект: Объект, условие, реквизиты: dict, параметры: dict, истина: bool) -> bool:
        """Сдвиг одного числа из условия на ±1 меняет его истинность."""
        имена: set[str] = set()
        в.имена_в(условие, имена)
        for имя in имена:
            for где in (реквизиты, параметры):
                значение = где.get(имя)
                if not isinstance(значение, (int, float)) or isinstance(значение, bool):
                    continue
                for сдвиг in (-1, 1):
                    р, п = dict(реквизиты), dict(параметры)
                    (р if где is реквизиты else п)[имя] = значение + сдвиг
                    if self.истинно(объект, условие, р, п) != истина:
                        return True
        return False


